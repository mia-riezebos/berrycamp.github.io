#!/usr/bin/env node
import fsp from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import { rgb2lab } from './lib/color.mjs';
import { colorpalette } from './lib/color-palette.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PALETTE_PATH = path.join(__dirname, 'lib', 'color-palette.mjs');

function toFixed(n) {
  return Number.isInteger(n) ? String(n) : n.toFixed(6).replace(/0+$/,'').replace(/\.$/,'');
}

function serializePaletteWithLab(palette) {
  const lines = [];
  lines.push('/** The color palette used by wplace.live');
  lines.push(' * @generated by scripts/update-palette-lab.mjs');
  lines.push(' */');
  lines.push('export const colorpalette = [');
  for (const entry of palette) {
    const [r, g, b] = entry.rgb;
    const lab = rgb2lab(entry.rgb);
    const labArr = `[${toFixed(lab[0])}, ${toFixed(lab[1])}, ${toFixed(lab[2])}]`;
    lines.push('    {');
    lines.push(`        name: ${JSON.stringify(entry.name)},`);
    lines.push(`        rgb: [${r}, ${g}, ${b}],`);
    lines.push(`        lab: ${labArr},`);
    lines.push(`        free: ${entry.free ? 'true' : 'false'},`);
    lines.push('    },');
  }
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const content = serializePaletteWithLab(colorpalette);
  await fsp.writeFile(PALETTE_PATH, content, 'utf8');
  // eslint-disable-next-line no-console
  console.log(`Updated ${PALETTE_PATH} with lab arrays for ${colorpalette.length} colors.`);
}

main().catch((err) => {
  // eslint-disable-next-line no-console
  console.error(err);
  process.exit(1);
});


